// Convert selected places into day-by-day ActivityItems
export function buildItineraryFromPlaces(
  destination: string,
  places: GeneratedPlace[]
): ActivityItem[] {
  const times = ['09:00 AM', '11:30 AM', '02:00 PM', '04:30 PM', '07:00 PM', '09:00 PM'];
  const typeMap: Record<string, 'visit' | 'beach' | 'dining' | 'activity'> = {
    'Sightseeing': 'visit',
    'Food & Dining': 'dining',
    'Beach': 'beach',
    'Culture': 'visit',
    'Nature': 'activity',
    'Activity': 'activity',
  };

  return places.map((place, idx) => ({
    id: `act-${Date.now()}-${idx + 1}`,
    orderNumber: idx + 1,
    time: times[idx % times.length],
    duration: place.duration,
    title: place.name,
    type: typeMap[place.category] || 'visit',
    categoryTag: place.category.toUpperCase(),
    isTopPick: idx === 0 || idx === 2,
    description: place.description,
    costInfo: place.estCost,
    rating: place.rating,
    reviewCount: '1.4k',
    highlightNote: `Top rated spot in ${destination}`,
    tags: place.tags,
    image: place.image,
    transitAfter:
      idx < places.length - 1
        ? {
            duration: '15 min',
            distance: '4.5 km',
            label: '15 min scenic transfer',
          }
        : undefined,
  }));
}
